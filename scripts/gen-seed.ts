// Generates supabase/seed.sql from the shared demo dataset.
// Run: npx tsx scripts/gen-seed.ts
import { writeFileSync } from 'node:fs';
import { buildLoadPlan, demoData } from '../packages/shared/src/index';

const d = demoData();
const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rows = (table: string, cols: string[], data: unknown[][]) =>
  data.length ? `insert into public.${table} (${cols.join(', ')}) values\n${data.map((r) => `  (${r.map(q).join(', ')})`).join(',\n')};\n` : '';

const out: string[] = ['-- Generated by scripts/gen-seed.ts — demo data (fictitious POs and serials)', 'begin;'];

out.push(rows('warehouses', ['id', 'code', 'name', 'type'], d.warehouses.map((w) => [w.id, w.code, w.name, w.type])));
out.push(rows('locations', ['id', 'warehouse_id', 'code', 'kind', 'x', 'y', 'z', 'capacity_cartons'], d.locations.map((l) => [l.id, l.warehouseId, l.code, l.kind, l.x, l.y, l.z, l.capacityCartons])));
out.push(rows('vendor_factory_map', ['vendor_system', 'vendor_factory_code', 'warehouse_id'], [['MERCURY', 'FAC-A01', 'wh-a'], ['MERCURY', 'FAC-B01', 'wh-b'], ['MERCURY', 'FAC-C01', 'wh-c']]));
out.push(rows('carton_codes', ['code', 'length_cm', 'width_cm', 'height_cm', 'max_stack'], [['A1', 59.7, 39.7, 20.3, 12], ['A6', 39.7, 30.5, 17.8, 14], ['A7', 39.7, 30.5, 10.2, 20]]));
out.push(rows('shipments', ['id', 'shipment_date', 'destination', 'ship_to_code', 'ship_method'], d.shipments.map((s) => [s.id, s.shipmentDate, s.destination, s.shipToCode, s.shipMethod])));
out.push(
  rows(
    'containers',
    ['id', 'code', 'shipment_id', 'type', 'container_no', 'truck_plate', 'driver_name', 'dock', 'loading_warehouse_id', 'status', 'planned_cartons', 'loaded_cartons', 'fill_volume_pct', 'loaded_kg', 'eta_done'],
    d.containers.map((c) => [c.id, c.code, c.shipmentId, c.type, c.containerNo, c.truckPlate, c.driverName, c.dock, c.loadingWarehouseId, c.status, c.plannedCartons, c.loadedCartons, c.fillVolumePct, c.loadedKg, c.etaDone]),
  ),
);
out.push(
  rows(
    'packing_plans',
    ['id', 'plan_ref', 'po_no', 'po_line', 'description', 'vendor_system', 'vendor_factory_code', 'factory_warehouse_id', 'shipment_id', 'source', 'status', 'version', 'totals', 'issue'],
    d.plans.map((p) => [p.id, p.planRef, p.poNo, p.poLine, p.description, p.vendorSystem, p.vendorFactoryCode, p.factoryWarehouseId, p.shipmentId, p.source, p.status, p.version, p.totals, p.issue]),
  ),
);
const rangeRows = Object.entries(d.ranges).flatMap(([planId, rs]) =>
  rs.map((r) => [planId, r.rangeNo, r.cartonFrom, r.cartonTo, r.serialFrom, r.serialTo, r.lineNo, r.style, r.poNo, r.poLine, r.color, r.size, r.styleColor, r.shipMethod, r.itemQty, r.qtyPerCarton, r.innerPkgCount, r.cartonCount, r.cartonCode, r.netNetKg, r.netKg, r.grossKg, r.lengthCm, r.widthCm, r.heightCm]),
);
out.push(rows('plan_carton_ranges', ['plan_id', 'range_no', 'carton_from', 'carton_to', 'serial_from', 'serial_to', 'line_no', 'style', 'po_no', 'po_line', 'color', 'size', 'style_color', 'ship_method', 'item_qty', 'qty_per_carton', 'inner_pkg_count', 'carton_count', 'carton_code', 'net_net_kg', 'net_kg', 'gross_kg', 'length_cm', 'width_cm', 'height_cm'], rangeRows));

// load sequence per container
const seq = new Map<string, { seq: number; label: string }>();
d.containers.forEach((c) => {
  const plan = buildLoadPlan(d.cartons.filter((x) => x.containerId === c.id), c.type);
  plan.steps.forEach((s) => seq.set(s.serial, { seq: s.seq, label: s.label }));
});
out.push(
  rows(
    'cartons',
    ['id', 'serial', 'style', 'color', 'size', 'qty', 'carton_code', 'length_cm', 'width_cm', 'height_cm', 'gross_kg', 'net_kg', 'po_no', 'po_line', 'plan_id', 'container_id', 'status', 'warehouse_id', 'location_id', 'load_seq', 'load_label'],
    d.cartons.map((c) => [c.id, c.serial, c.style, c.color, c.size, c.qty, c.cartonCode, c.lengthCm, c.widthCm, c.heightCm, c.grossKg, c.netKg, c.poNo, c.poLine, c.planId, c.containerId, c.status, c.warehouseId, c.locationId, seq.get(c.serial)?.seq ?? null, seq.get(c.serial)?.label ?? null]),
  ),
);
out.push(rows('agent_actions', ['id', 'agent', 'text', 'result', 'status', 'confidence', 'created_at'], d.actions.map((a) => [a.id, a.agent, a.text, a.result, a.status, a.confidence, a.createdAt])));
out.push(rows('decisions', ['id', 'kind', 'title', 'recommendation', 'confidence', 'primary_action'], d.decisions.map((x) => [x.id, x.kind, x.title, x.recommendation, x.confidence, x.primaryAction])));
out.push('commit;');

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`seed.sql: ${d.cartons.length} cartons, ${d.plans.length} plans, ${d.containers.length} containers`);
